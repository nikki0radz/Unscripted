const extract=(start,end)=>app.slice(app.indexOf(start),app.indexOf(end,app.indexOf(start)));
const context={state:{entries:[]},transcriptText:e=>e.text,searchableParts:e=>[{part:{createdAt:e.createdAt},text:e.text}]};
